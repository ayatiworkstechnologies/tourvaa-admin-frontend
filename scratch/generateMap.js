const dots = [];
for (let r = 0; r < rawMap.length; r++) {
  const line = rawMap[r];
  for (let c = 0; c < line.length; c++) {
    if (line[c] === '1') {
      dots.push([c, r]);
    }
  }
}

console.log(`Generated ${dots.length} dots.`);
fs.writeFileSync('scratch/dots.json', JSON.stringify(dots));
